function detectLang() {
  const fromUrl = new URLSearchParams(location.search).get("lang");
  if (fromUrl in STRINGS) return fromUrl;
  try { const saved = localStorage.getItem("64sq-lang"); if (saved in STRINGS) return saved; } catch (_) { /* storage unavailable */ }
  const browser = (navigator.languages || [navigator.language || ""]).find(Boolean) || "";
  return browser.toLowerCase().startsWith("fr") ? "fr" : "en";
}

let LANG = detectLang();

function t(key, vars = {}) {
  const text = STRINGS[LANG][key] ?? STRINGS.fr[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (m, name) => (name in vars ? String(vars[name]) : m));
}

function applyStatic() {
  const root = document.documentElement;
  root.lang = LANG;
  document.title = t("doc.title");
  document.querySelector('meta[name="description"]').content = t("doc.description");
  document.querySelectorAll("[data-i18n]").forEach((el) => { el.textContent = t(el.dataset.i18n); });
  document.querySelectorAll("[data-i18n-aria]").forEach((el) => el.setAttribute("aria-label", t(el.dataset.i18nAria)));
  const other = LANG === "fr" ? "en" : "fr";
  document.querySelectorAll(".lang-toggle").forEach((btn) => { btn.lang = other; });
}

function setLang(lang) {
  LANG = lang;
  try { localStorage.setItem("64sq-lang", lang); } catch (_) { /* storage unavailable */ }
  const url = new URL(location.href);
  url.searchParams.set("lang", lang);
  history.replaceState(null, "", url);
  applyStatic();
}

